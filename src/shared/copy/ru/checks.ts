function pluralPoints(n: number): string {
  const mod100 = n % 100;
  const mod10 = n % 10;
  if (mod100 >= 11 && mod100 <= 14) return `${n} пунктов`;
  if (mod10 === 1) return `${n} пункт`;
  if (mod10 >= 2 && mod10 <= 4) return `${n} пункта`;
  return `${n} пунктов`;
}

